#!/usr/bin/env python3
"""Regenerate the gem-art index and the app's copies from preview/assets/gems.

`preview/assets/gems/<slug>.png` is the source of truth: 507 Path of Exile skill
gem icons (78px, palettised) extracted from MuffinsBeGreat/PoE-Gems. This script

  * writes `preview/assets/gems/index.json` so the browser preview knows which
    slugs exist (and which gem has no art before it requests a 404);
  * mirrors the set into `src/ForeverExiled.App/Resources/Images/gem_<slug>.png`
    at 64px, which is what MAUI's `Resources/Images/*` glob picks up;
  * regenerates `src/ForeverExiled.App/Theming/GemArt.g.cs`, the C# lookup with
    the same exact-then-variant rule as the preview.

Run it after adding or replacing gem art:  python3 tools/sync_gem_art.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "preview" / "assets" / "gems"
APP_IMAGES = ROOT / "src" / "ForeverExiled.App" / "Resources" / "Images"
CS_TARGET = ROOT / "src" / "ForeverExiled.App" / "Theming" / "GemArt.g.cs"

APP_SIZE = 64


def main() -> None:
    slugs = sorted(p.stem for p in SRC.glob("*.png"))
    if not slugs:
        raise SystemExit(f"no gem art in {SRC.relative_to(ROOT)}")

    (SRC / "index.json").write_text(
        json.dumps({"count": len(slugs), "slugs": slugs}, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )

    APP_IMAGES.mkdir(parents=True, exist_ok=True)
    for stale in APP_IMAGES.glob("gem_*.png"):
        stale.unlink()

    for slug in slugs:
        image = Image.open(SRC / f"{slug}.png").convert("RGBA")
        small = image.resize((APP_SIZE, APP_SIZE), Image.LANCZOS)
        small.quantize(colors=192, method=Image.Quantize.FASTOCTREE).save(
            APP_IMAGES / f"gem_{slug}.png", optimize=True
        )

    lines = []
    for chunk in range(0, len(slugs), 4):
        lines.append("        " + ", ".join(f'"{s}"' for s in slugs[chunk:chunk + 4]) + ",")
    table = "\n".join(lines)

    CS_TARGET.write_text(
        f'''// <auto-generated>
//   Regenerate with `python3 tools/sync_gem_art.py`; do not edit by hand.
//   {len(slugs)} skill gem icons from preview/assets/gems.
// </auto-generated>
namespace ForeverExiled.App.Theming;

/// <summary>Skill gem icons shipped in Resources/Images as gem_&lt;slug&gt;.png.</summary>
public static class GemArt
{{
    /// <summary>Every gem that has art, alphabetical.</summary>
    private static readonly string[] Slugs =
    {{
{table}
    }};

    private static readonly HashSet<string> Lookup = new(Slugs, StringComparer.Ordinal);

    /// <summary>"Ice Nova of Frostbolts" → "ice_nova_of_frostbolts".</summary>
    public static string Slug(string? skillName)
    {{
        if (string.IsNullOrWhiteSpace(skillName))
        {{
            return string.Empty;
        }}

        var lowered = skillName.Trim().ToLowerInvariant()
            .Replace("'", string.Empty, StringComparison.Ordinal)
            .Replace(",", string.Empty, StringComparison.Ordinal)
            .Replace(".", string.Empty, StringComparison.Ordinal)
            .Replace("_", " ", StringComparison.Ordinal);

        var builder = new System.Text.StringBuilder(lowered.Length);
        var previousWasSpace = false;
        foreach (var ch in lowered)
        {{
            if (ch is >= 'a' and <= 'z' || ch is >= '0' and <= '9')
            {{
                builder.Append(ch);
                previousWasSpace = false;
            }}
            else if (!previousWasSpace)
            {{
                builder.Append('_');
                previousWasSpace = true;
            }}
        }}

        return builder.ToString().Trim('_');
    }}

    /// <summary>
    /// Icon file name for a main skill, or an empty string when the gem has no art.
    /// Falls back to a variant gem ("Raise Spectre" → "Raise Spectre of Transience")
    /// because transmuted gems share the base skill's artwork.
    /// </summary>
    public static string ImageFor(string? skillName)
    {{
        var slug = Slug(skillName);
        if (slug.Length == 0)
        {{
            return string.Empty;
        }}

        if (Lookup.Contains(slug))
        {{
            return "gem_" + slug + ".png";
        }}

        var prefix = slug + "_";
        foreach (var candidate in Slugs)
        {{
            if (candidate.StartsWith(prefix, StringComparison.Ordinal))
            {{
                return "gem_" + candidate + ".png";
            }}
        }}

        return string.Empty;
    }}

    public static bool Has(string? skillName) => ImageFor(skillName).Length > 0;
}}
''',
        encoding="utf-8",
    )

    print(f"index: {len(slugs)} gems")
    print(f"app copies: {len(slugs)} → {(APP_IMAGES / 'gem_*.png').relative_to(ROOT)}")
    print(f"c# index: {CS_TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
