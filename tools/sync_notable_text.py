#!/usr/bin/env python3
"""Regenerate the app's notable-text lookup from preview/assets/notables.json.

`preview/assets/notables.json` is the source of truth (built by
tools/build_notable_text.py from Path of Building's tree data). The preview loads
it directly; the app gets the same content compiled in, as `Theming/NotableText.g.cs`.

    python3 tools/sync_notable_text.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "preview" / "assets" / "notables.json"
TARGET = ROOT / "src" / "ForeverExiled.App" / "Theming" / "NotableText.g.cs"


def literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def table(name: str, entries: list[tuple[str, list[str]]]) -> str:
    if not entries:
        return ""
    rows = []
    for key, lines in entries:
        if not lines:
            continue
        joined = ", ".join(literal(line) for line in lines)
        rows.append(f'        [{literal(key)}] = new[] {{ {joined} }},')
    return (
        f"    private static readonly Dictionary<string, string[]> {name} = new(StringComparer.OrdinalIgnoreCase)\n"
        "    {\n" + "\n".join(rows) + "\n    };\n"
    )


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    notables: dict[str, dict] = data["notables"]

    stats = [(name, entry.get("stats", [])) for name, entry in notables.items()]
    reminders = [(name, entry.get("reminder", [])) for name, entry in notables.items()]

    body = table("Stats", stats) + "\n" + table("Reminders", reminders)

    TARGET.write_text(
        f"""// <auto-generated>
//   Regenerate with `python3 tools/sync_notable_text.py`; do not edit by hand.
//   {len(notables)} cluster-jewel notables from preview/assets/notables.json.
// </auto-generated>
namespace ForeverExiled.App.Theming;

/// <summary>
/// What each cluster-jewel notable passive actually grants, so the item card can
/// print the effect under "1 Added Passive Skill is X" the way the game does.
/// </summary>
public static class NotableText
{{
{body}
    /// <summary>Stat lines for a notable; empty when we have no text for it.</summary>
    public static IReadOnlyList<string> StatsFor(string? notableName)
    {{
        var key = (notableName ?? string.Empty).Trim();
        return key.Length > 0 && Stats.TryGetValue(key, out var lines) ? lines : Array.Empty<string>();
    }}

    /// <summary>Reminder text (the game's grey parentheticals), usually empty.</summary>
    public static IReadOnlyList<string> RemindersFor(string? notableName)
    {{
        var key = (notableName ?? string.Empty).Trim();
        return key.Length > 0 && Reminders.TryGetValue(key, out var lines) ? lines : Array.Empty<string>();
    }}
}}
""",
        encoding="utf-8",
    )

    print(f"c# notables: {len(notables)} → {TARGET.relative_to(ROOT)}")
    print(f"  size={TARGET.stat().st_size / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
