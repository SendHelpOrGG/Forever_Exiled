#!/usr/bin/env python3
"""
Turn preview/assets/notable_weights.json into the C# registry the app reads.

    python3 tools/build_notable_weights.py /tmp/ModJewelCluster.lua /tmp/ClusterJewels.lua
    python3 tools/sync_notable_weights.py

Writes src/ForeverExiled.App/Theming/NotableWeights.g.cs.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "preview" / "assets" / "notable_weights.json"
OUT = ROOT / "src" / "ForeverExiled.App" / "Theming" / "NotableWeights.g.cs"


def cs_text(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    categories = data["categories"]
    notables = data["notables"]
    grants = data["grants"]

    lines: list[str] = []
    lines.append("// <auto-generated>")
    lines.append("//   Regenerate with `python3 tools/sync_notable_weights.py`; do not edit by hand.")
    lines.append(f"//   {len(notables)} cluster-jewel notables across {len(categories)} cluster bases,")
    lines.append("//   from the game's mod data (see tools/build_notable_weights.py).")
    lines.append("// </auto-generated>")
    lines.append("namespace ForeverExiled.App.Theming;")
    lines.append("")
    lines.append("/// <summary>")
    lines.append("/// Spawn weights of the cluster-jewel notables: how heavy each one is inside the pool")
    lines.append("/// its base rolls from, so the item card can say how hard it is to roll.")
    lines.append("/// </summary>")
    lines.append("public static class NotableWeights")
    lines.append("{")
    lines.append(f'    public const string Source = "PoE mod data via Path of Building, {date.today().isoformat()}";')
    lines.append("")

    lines.append("    private static readonly Dictionary<string, string> PoolLabels = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        lines.append(f"        [{cs_text(tag)}] = {cs_text(category['label'])},")
    lines.append("    };")
    lines.append("")

    lines.append("    private static readonly Dictionary<string, int> PoolCounts = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        lines.append(f"        [{cs_text(tag)}] = {len(category['notables'])},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, string[]> PoolSizes = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        sizes = ", ".join(cs_text(s) for s in category["sizes"])
        lines.append(f"        [{cs_text(tag)}] = new[] {{ {sizes} }},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, int> PoolTotals = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        for kind, slot in sorted(category.get("pools", {}).items()):
            for size, total in sorted(slot["total"].items()):
                # the totals block also carries the tag/generic split; only sizes are numbers
                if not isinstance(total, int):
                    continue
                lines.append(f"        [{cs_text(f'{tag}|{size}|{kind}')}] = {total},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, string> PoolLevels = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        for kind, slot in sorted(category.get("pools", {}).items()):
            for size, points in sorted(slot.get("levels", {}).items()):
                packed = "|".join(f"{level}:{weight}" for level, weight in points)
                lines.append(f"        [{cs_text(f'{tag}|{size}|{kind}')}] = {cs_text(packed)},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, int> PoolModCounts = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for tag, category in sorted(categories.items()):
        for kind, slot in sorted(category.get("pools", {}).items()):
            count = slot.get("count", 0) + slot.get("genericCount", 0)
            lines.append(f"        [{cs_text(f'{tag}|{kind}')}] = {count},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, int> Levels = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for key, entry in sorted(notables.items()):
        lines.append(f"        [{cs_text(key)}] = {entry.get('level', 1)},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, string> Types = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for key, entry in sorted(notables.items()):
        lines.append(f"        [{cs_text(key)}] = {cs_text(entry.get('type', ''))},")
    lines.append("    };")
    lines.append("")

    lines.append('    private static readonly Dictionary<string, string[]> Tags = new(StringComparer.OrdinalIgnoreCase)')
    lines.append("    {")
    for key, entry in sorted(notables.items()):
        tags = ", ".join(cs_text(t) for t in entry.get("tags", []))
        lines.append(f"        [{cs_text(key)}] = new[] {{ {tags} }},")
    lines.append("    };")
    lines.append("")

    lines.append("    private static readonly Dictionary<string, string> Grants = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for key, tag in sorted(grants.items()):
        lines.append(f"        [{cs_text(key)}] = {cs_text(tag)},")
    lines.append("    };")
    lines.append("")

    lines.append("    private static readonly Dictionary<string, string> Weights = new(StringComparer.OrdinalIgnoreCase)")
    lines.append("    {")
    for key, entry in sorted(notables.items()):
        # packed as "tag:weight|tag:weight" so the generated file stays readable
        packed = "|".join(f"{tag}:{weight}" for tag, weight in sorted(entry["weights"].items()))
        lines.append(f"        [{cs_text(key)}] = {cs_text(packed)},")
    lines.append("    };")
    lines.append("")

    lines.append("""    /// <summary>The pool a base rolls from, from its size and its "Added Small Passive Skills grant" line.</summary>
    public static string? PoolFor(string? size, string? grant)
    {
        if (string.IsNullOrWhiteSpace(grant))
        {
            return null;
        }

        var key = grant.Trim().ToLowerInvariant();
        var sizeKey = (size ?? string.Empty).Trim().ToLowerInvariant();
        var normalised = Normalize(key);

        if (Grants.TryGetValue(sizeKey + "|" + key, out var tag)
            || Grants.TryGetValue("any|" + key, out tag)
            || Grants.TryGetValue(sizeKey + "~" + normalised, out tag)
            || Grants.TryGetValue("any~" + normalised, out tag))
        {
            return tag;
        }

        return null;
    }

    /// <summary>The heaviest pool a notable belongs to, when only its size is known.</summary>
    public static string? BestPoolFor(string? notable, string? size)
    {
        var weights = WeightsOf(notable);
        if (weights is null)
        {
            return null;
        }

        string? best = null;
        var bestWeight = 0;
        foreach (var pair in weights)
        {
            if (!PoolLabels.ContainsKey(pair.Key))
            {
                continue;
            }

            if (size is { Length: > 0 } && PoolSizes.TryGetValue(pair.Key, out var sizes)
                && Array.IndexOf(sizes, size) < 0)
            {
                continue;
            }

            if (pair.Value > bestWeight)
            {
                best = pair.Key;
                bestWeight = pair.Value;
            }
        }

        return best;
    }

    public static string PoolLabel(string? tag) =>
        tag is not null && PoolLabels.TryGetValue(tag, out var label) ? label : string.Empty;

    public static int PoolNotables(string? tag) =>
        tag is not null && PoolCounts.TryGetValue(tag, out var count) ? count : 0;

    /// <summary>
    /// How many mods compete for one affix slot: the base tag's notables plus the generic
    /// small-passive grants that roll on every cluster jewel of that size.
    /// </summary>
    public static int PoolMods(string? tag, string? kind) =>
        tag is not null && kind is not null && PoolModCounts.TryGetValue(tag + "|" + kind, out var count)
            ? count
            : 0;

    /// <summary>Weight of one affix pool ("Prefix"/"Suffix") for a size.</summary>
    public static int PoolTotal(string? tag, string? size, string? kind) =>
        PoolTotal(tag, size, kind, 0);

    /// <summary>
    /// Weight of an affix pool as it stands at an item level: a mod only competes for a
    /// slot once the base is high enough, so an iLvl 68 jewel rolls a smaller pool.
    /// </summary>
    public static int PoolTotal(string? tag, string? size, string? kind, int itemLevel)
    {
        if (tag is null)
        {
            return 0;
        }

        var key = tag + "|" + (size ?? string.Empty) + "|" + (kind ?? string.Empty);
        if (itemLevel > 0 && PoolLevels.TryGetValue(key, out var packed))
        {
            var total = 0;
            foreach (var point in packed.Split('|', StringSplitOptions.RemoveEmptyEntries))
            {
                var split = point.IndexOf(':');
                if (split <= 0 || !int.TryParse(point[..split], out var level))
                {
                    continue;
                }

                if (level > itemLevel)
                {
                    break;
                }

                if (int.TryParse(point[(split + 1)..], out var weight))
                {
                    total = weight;
                }
            }

            if (total > 0)
            {
                return total;
            }
        }

        return PoolTotals.TryGetValue(key, out var full) ? full : 0;
    }

    /// <summary>The item level a notable needs before it can roll.</summary>
    public static int LevelFor(string? notable) =>
        notable is not null && Levels.TryGetValue(notable.Trim(), out var level) ? level : 1;

    /// <summary>Prefix or Suffix - the slot a notable occupies.</summary>
    public static string TypeFor(string? notable) =>
        notable is not null && Types.TryGetValue(notable.Trim(), out var type) ? type : string.Empty;

    /// <summary>The game's mod tags for a notable (fossils, harvest and influences key off these).</summary>
    public static string[] TagsFor(string? notable) =>
        notable is not null && Tags.TryGetValue(notable.Trim(), out var tags) ? tags : Array.Empty<string>();

    public static int WeightFor(string? notable, string? tag)
    {
        var weights = WeightsOf(notable);
        return weights is not null && tag is not null && weights.TryGetValue(tag, out var weight) ? weight : 0;
    }

    /// <summary>Chance of rolling this notable, as a percentage of its base's pool.</summary>
    public static double ChancePercent(string? notable, string? tag, string? size, int itemLevel = 0)
    {
        var total = PoolTotal(tag, size, TypeFor(notable), itemLevel);
        return total <= 0 ? 0 : WeightFor(notable, tag) * 100.0 / total;
    }

    private static Dictionary<string, int>? WeightsOf(string? notable)
    {
        if (string.IsNullOrWhiteSpace(notable) || !Weights.TryGetValue(notable.Trim(), out var packed))
        {
            return null;
        }

        var parsed = new Dictionary<string, int>(StringComparer.OrdinalIgnoreCase);
        foreach (var part in packed.Split('|', StringSplitOptions.RemoveEmptyEntries))
        {
            var split = part.LastIndexOf(':');
            if (split > 0 && int.TryParse(part[(split + 1)..], out var value))
            {
                parsed[part[..split]] = value;
            }
        }

        return parsed;
    }

    private static string Normalize(string text)
    {
        var builder = new System.Text.StringBuilder(text.Length);
        foreach (var c in text)
        {
            // "12% increased fire damage" and "10% increased fire damage" share a pool
            builder.Append(char.IsDigit(c) || c == '%' || c == '.' ? ' ' : c);
        }

        return string.Join(' ', builder.ToString().Split(' ', StringSplitOptions.RemoveEmptyEntries));
    }""")
    lines.append("}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.1f} KiB)")
    print(f"  pools={len(categories)} grants={len(grants)} notables={len(notables)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
