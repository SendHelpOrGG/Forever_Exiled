#!/usr/bin/env python3
"""Syntax-check every C# file in the repo with tree-sitter.

The sandbox has no .NET SDK (and MAUI cannot build on Linux anyway), so this is the
closest thing to a compiler pass: it parses each file with the official C# grammar and
reports syntax errors plus unresolved `using` namespaces that don't exist in the tree.

It also catches the two mistakes generated files make that the grammar happily accepts
but the compiler rejects: `new[] { }` (CS0826, nothing to infer the element type from)
and nullable annotations in an auto-generated file without a `#nullable` context (CS8669).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import tree_sitter_c_sharp
from tree_sitter import Language, Parser

ROOT = Path(__file__).resolve().parents[1]
LANGUAGE = Language(tree_sitter_c_sharp.language())


def walk(node):
    stack = [node]
    while stack:
        current = stack.pop()
        yield current
        stack.extend(current.children)


def main() -> int:
    parser = Parser(LANGUAGE)
    files = sorted(p for p in ROOT.rglob("*.cs") if "/obj/" not in str(p) and "/bin/" not in str(p))
    failures = 0
    for path in files:
        source = path.read_bytes()
        tree = parser.parse(source)
        problems = []
        for node in walk(tree.root_node):
            if node.type == "ERROR":
                problems.append((node.start_point, "ERROR", source[node.start_byte:node.end_byte][:120]))
            elif node.is_missing:
                problems.append((node.start_point, f"missing {node.type}", b""))
        text = source.decode("utf-8", "replace")
        for match in re.finditer(r"new\[\]\s*\{\s*\}", text):
            row = text.count("\n", 0, match.start())
            problems.append(
                ((row, 0), "empty implicitly-typed array (CS0826) — name the type or Array.Empty<T>()", b""))
        # a type from another namespace needs its using: the compiler only searches the
        # enclosing namespaces, so ForeverExiled.App.ViewModels does not see .Theming
        theming_types = r"\b(NotableWeights|NotableText|GemArt|TagColors|Palette|CurrencyPrices)\b"
        if ('namespace ForeverExiled.App.Theming' not in text
                and "using ForeverExiled.App.Theming;" not in text
                and re.search(theming_types, text)):
            problems.append(
                ((0, 0), "uses a Theming type without `using ForeverExiled.App.Theming;` (CS0103)", b""))

        # the toolkit's attributes are not in the implicit usings either: a partial class that
        # gains an [ObservableProperty] without this using fails with CS0246 on every field
        toolkit_namespace = 'namespace CommunityToolkit.Mvvm' in text
        if (not toolkit_namespace
                and "using CommunityToolkit.Mvvm.ComponentModel;" not in text
                and re.search(r"\[\s*(ObservableProperty|NotifyPropertyChangedFor|NotifyCanExecuteChangedFor)\b", text)):
            problems.append(
                ((0, 0),
                 "uses a CommunityToolkit attribute without `using CommunityToolkit.Mvvm.ComponentModel;` (CS0246)",
                 b""))

        if (not toolkit_namespace
                and "using CommunityToolkit.Mvvm.Input;" not in text
                and re.search(r"\[\s*RelayCommand\b", text)):
            problems.append(
                ((0, 0),
                 "uses [RelayCommand] without `using CommunityToolkit.Mvvm.Input;` (CS0246)",
                 b""))

        if re.search(r"\bIAsyncRelayCommand\b|\bAsyncRelayCommand\b|\bnew RelayCommand\b", text):
            if not toolkit_namespace and "using CommunityToolkit.Mvvm.Input;" not in text:
                problems.append(
                    ((0, 0),
                     "uses a CommunityToolkit command without `using CommunityToolkit.Mvvm.Input;` (CS0246)",
                     b""))

        # the flex enums live in Microsoft.Maui.Layouts, not in Controls: without the using,
        # FlexDirection/FlexWrap/FlexJustify are CS0103 even though FlexLayout itself resolves
        if ('namespace Microsoft.Maui.Layouts' not in text
                and "using Microsoft.Maui.Layouts;" not in text
                and re.search(r"\b(FlexDirection|FlexWrap|FlexJustify|FlexAlignItems|FlexAlignContent|FlexAlignSelf|FlexBasis)\b", text)):
            problems.append(
                ((0, 0), "uses a flex layout enum without `using Microsoft.Maui.Layouts;` (CS0103)", b""))

        # Measure() already returns a Size in MAUI; .Request is the old Xamarin.Forms shape
        if re.search(r"Measure\s*\([^;]*\)\s*\.Request\b", text):
            problems.append(
                ((0, 0),
                 "Measure() returns a Size - .Request does not exist on it (CS1061)",
                 b""))

        if text.startswith("// <auto-generated>") and "#nullable" not in text and "string?" in text:
            problems.append(
                ((0, 0), "nullable annotations without #nullable (CS8669)", b""))

        if problems:
            failures += 1
            print(f"\n{path.relative_to(ROOT)}")
            for (row, col), kind, snippet in problems[:6]:
                text = snippet.decode("utf-8", "replace").replace("\n", "\\n")
                print(f"  {row + 1}:{col + 1}  {kind}  {text}")
    print(f"\n{len(files)} files parsed, {failures} with syntax problems")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
