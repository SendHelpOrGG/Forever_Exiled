#!/usr/bin/env python3
"""Generate src/ForeverExiled.App/Theming/TagColors.g.cs from preview/assets/tag_colors.json.

The preview and the app must agree on what a mod tag looks like, so the palette lives in
one JSON file and this script mirrors it into C#. Run it after editing the JSON:

    python3 tools/sync_tag_colors.py

Generated, do not edit by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'preview' / 'assets' / 'tag_colors.json'
TARGET = ROOT / 'src' / 'ForeverExiled.App' / 'Theming' / 'TagColors.g.cs'

HEADER = '''// <auto-generated>
//     Generated by tools/sync_tag_colors.py from preview/assets/tag_colors.json.
//     Do not edit this file by hand - change the JSON and re-run the script.
// </auto-generated>

namespace ForeverExiled.App.Theming;

/// <summary>
/// One colour per mod tag, mirroring the chips the preview draws. Tags are the words the
/// game gates a cluster notable with (fire, damage, speed...), so the hue groups them by
/// family: warm reds for damage, one hue per element, blues for mana and energy shield,
/// greens for resistances and speed. Decoration only - never an input to any odds number.
/// </summary>
public static class TagColors
{
    /// <summary>What an unknown tag gets: the same neutral magic blue the preview falls back to.</summary>
    public const string Default = "__DEFAULT__";

    private static readonly Dictionary<string, string> HexByTag = new(StringComparer.OrdinalIgnoreCase)
    {
__ENTRIES__
    };

    /// <summary>The tag's palette entry, or <see cref="Default"/> when it has none.</summary>
    public static string HexFor(string? tag)
    {
        var key = Normalize(tag);
        return key.Length > 0 && HexByTag.TryGetValue(key, out var hex) ? hex : Default;
    }

    public static Color TextColorFor(string? tag) => Color.FromArgb(HexFor(tag));

    /// <summary>The 12% tint the chip sits on.</summary>
    public static Color TintColorFor(string? tag) => TextColorFor(tag).WithAlpha(0.12f);

    /// <summary>The 30% edge that keeps the chip readable on the dark panel.</summary>
    public static Color BorderColorFor(string? tag) => TextColorFor(tag).WithAlpha(0.30f);

    /// <summary>"Chaos_Damage" / " chaos damage " both resolve to the same chip colour.</summary>
    public static string Normalize(string? tag) =>
        string.Join('_', (tag ?? string.Empty).Trim().ToLowerInvariant()
            .Replace('-', '_').Split(' ', StringSplitOptions.RemoveEmptyEntries));
}
'''


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    tags = data.get('tags') or {}
    if not tags:
        raise SystemExit('no tags in ' + str(SOURCE))

    entries = []
    width = max(len(tag) for tag in tags)  # keeps the initializer columns aligned
    for tag in sorted(tags):
        entries.append(f'        ["{tag}"] = "{tags[tag]}",'.ljust(width + 30).rstrip())
    # drop the trailing comma of the last initializer for tidiness
    entries[-1] = entries[-1].rstrip().rstrip(',')

    text = HEADER.replace('__DEFAULT__', data.get('default', '#8888ff')) \
        .replace('__ENTRIES__', '\n'.join(entries))
    TARGET.write_text(text, encoding='utf-8')
    print(f'  tags={len(tags)} -> {TARGET.relative_to(ROOT)} ({TARGET.stat().st_size / 1024:.1f} KiB)')


if __name__ == '__main__':
    main()
